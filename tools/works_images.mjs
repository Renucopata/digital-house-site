// Project photos (new design): brand-assets/new-design/works/<folder>/imgN.* → public/works/<slug>/NN.webp
// plus src/content/work-images.ts (paths + sizes, in the photographer's numbered order).
//   npm run works:images
// Originals are never modified. Max 1800 px wide, WebP q82. img1 is the project's cover.
import { mkdir, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import sharp from "sharp";

const SRC = "brand-assets/new-design/works";
const OUT = "public/works";
const TS = "src/content/work-images.ts";
const MAX_WIDTH = 1800;

/** folder name in brand-assets → project slug used on the site */
const FOLDERS = {
  canel_rol: "canel-roll",
  fury_cup: "fury-cup",
  vida: "vida",
  zaleriz: "zareliz",
  // add new projects here, e.g. bosque_sur: "bosque-sur"
};

const result = {};
for (const [folder, slug] of Object.entries(FOLDERS)) {
  let files;
  try {
    files = (await readdir(join(SRC, folder))).filter((f) => /^img\d+\.(jpe?g|png|webp)$/i.test(f));
  } catch {
    console.warn(`skip ${slug}: ${join(SRC, folder)} not found`);
    continue;
  }
  files.sort((a, b) => parseInt(a.match(/\d+/)[0], 10) - parseInt(b.match(/\d+/)[0], 10));
  await mkdir(join(OUT, slug), { recursive: true });
  result[slug] = [];
  for (const [i, file] of files.entries()) {
    const name = `${String(i + 1).padStart(2, "0")}.webp`;
    const out = join(OUT, slug, name);
    const info = await sharp(join(SRC, folder, file))
      .rotate()
      .resize({ width: MAX_WIDTH, withoutEnlargement: true })
      .webp({ quality: 82, effort: 6 })
      .toFile(out);
    result[slug].push({ src: `/works/${slug}/${name}`, width: info.width, height: info.height });
    console.log(`${out.padEnd(34)} ${`${info.width}x${info.height}`.padStart(10)} ${`${(info.size / 1024).toFixed(0)} KB`.padStart(7)}  ← ${folder}/${file}`);
  }
}

await writeFile(
  TS,
  `// Generated by tools/works_images.mjs (npm run works:images). Do not edit by hand.
// Project photos in their numbered order; the first one is the cover.

export type WorkImage = { src: string; width: number; height: number };

export const workImages: Record<string, WorkImage[]> = ${JSON.stringify(result, null, 2)};
`,
);
console.log(`wrote ${TS}`);
